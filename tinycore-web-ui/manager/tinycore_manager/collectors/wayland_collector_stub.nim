proc onSurfaceCreate(collector: WaylandCollector, surface: WlrSurface) =
  ## Handle new Wayland surface (window created)
  let resourceId = fmt"window:wl-{collector.nextWindowId:04x}"
  collector.nextWindowId += 1
  
  # Emit resource.create event
  let payload = %* {
    "id": resourceId,
    "payload": {
      "title": surface.title,
      "appId": surface.appId,
      "geometry": {
        "width": surface.width,
        "height": surface.height
      },
      "state": "active",
      "capabilities": ["resize", "move", "close"]
    },
    "meta": {
      "component": "window.v1",
      "version": 1
    }
  }
  collector.registry.emitProc("resource.create", payload)
  
  # Create encoder and stream
  let encoder = createEncoder(
    codec = "H264",
    width = surface.width,
    height = surface.height,
    fps = 30,
    bitrate = 2000  # 2 Mbps
  )
  
  # Emit stream.start event
  let streamPayload = %* {
    "type": "stream.start",
    "id": fmt"stream:{resourceId}",
    "payload": {
      "resource": resourceId,
      "media": {
        "kind": "video",
        "codec": "H264",
        "width": surface.width,
        "height": surface.height,
        "fps": 30
      },
      "transport": {
        "kind": "webrtc",
        "offer": "v=0..."  # Real SDP generated by WebRTC stack
      }
    }
  }
  collector.registry.emitProc("stream.start", streamPayload)
  
  # Track window
  let window = WaylandWindow(
    resourceId: resourceId,
    surface: surface,
    encoder: encoder,
    lastFrameTime: 0.0
  )
  collector.windows[resourceId] = window
  
  echo fmt"Created window resource: {resourceId}"

proc onSurfaceCommit(collector: WaylandCollector, surface: WlrSurface) =
  ## Handle surface buffer commit (new frame available)
  let resourceId = fmt"window:wl-{surface.id}"
  let window = collector.windows.getOrDefault(resourceId)
  if window.isNil:
    return
  
  # Get current buffer
  let buffer = wlrSurfaceGetBuffer(surface)
  
  # Encode frame
  let encodedFrame = window.encoder.encode(buffer)
  
  # Send via WebRTC
  sendFrame(encodedFrame)
  
  window.lastFrameTime = epochTime()

proc onSurfaceDestroy(collector: WaylandCollector, surface: WlrSurface) =
  ## Handle surface destruction (window closed)
  let resourceId = fmt"window:wl-{surface.id}"
  
  # Stop stream
  let streamPayload = %* {
    "type": "stream.stop",
    "id": fmt"stream:{resourceId}",
    "meta": {
      "reason": "surface_destroyed"
    }
  }
  collector.registry.emitProc("stream.stop", streamPayload)
  
  # Delete resource
  let deletePayload = %* {
    "type": "resource.delete",
    "id": resourceId,
    "meta": {
      "reason": "closed"
    }
  }
  collector.registry.emitProc("resource.delete", deletePayload)
  
  # Remove from tracking
  collector.windows.del(resourceId)
  echo fmt"Destroyed window resource: {resourceId}"

